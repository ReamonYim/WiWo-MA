        self.preflight_job=ROOT/'artifacts/platform/validation'/('web_preflight_'+str(time.time_ns()))
        self.preflight_job.mkdir(parents=True,exist_ok=False)
        atomic_json(self.preflight_job/'config.json',self.controller.config)
        env=dict(os.environ,CUDA_VISIBLE_DEVICES='',WIWO_GPU='-1',PYTHONPATH=str(ROOT/'src'),OPENBLAS_NUM_THREADS='2',OMP_NUM_THREADS='2')
        with (self.preflight_job/'cpu.log').open('wb') as log:
            self.preflight_process=subprocess.Popen([sys.executable,'-m','wiwo_ma.platform.cli','preflight','--config',str(self.preflight_job/'config.json'),
                '--output',str(self.preflight_job/'result')],cwd=ROOT,env=env,stdout=log,stderr=subprocess.STDOUT,start_new_session=True)
        return dict(status='CPU_preflight_running',pid=self.preflight_process.pid,new_GPU_seconds=0,output=str(self.preflight_job.relative_to(ROOT)))

