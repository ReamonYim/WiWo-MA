class API:
    def __init__(self,ui,host,port):
        outer=self;self.ui=ui
        class Handler(BaseHTTPRequestHandler):
            def log_message(self,*args):pass
            def reply(self,status,value):
                data=json.dumps(plain(value),allow_nan=False).encode();self.send_response(status)
                self.send_header('Content-Type','application/json');self.send_header('Content-Length',str(len(data)));self.end_headers();self.wfile.write(data)
            def do_HEAD(self):
                try:
                    if self.path!='/api/dataset':self.reply(404,dict(error='Unknown route'));return
                    path=ui.export_dataset();self.send_response(200);self.send_header('Content-Type','application/x-hdf5');self.send_header('Content-Length',str(path.stat().st_size));self.end_headers()
                except Exception as e:self.reply(400,dict(error=str(e)))
            def do_GET(self):
                try:
                    path=urllib.parse.urlsplit(self.path).path;s,r,stats=ui.controller.snapshot()
                    if path=='/api/dataset':
                        file=ui.export_dataset();size=file.stat().st_size;begin,end=0,size-1
                        request=self.headers.get('Range')
                        if request:
                            match=re.fullmatch(r'bytes=(\d+)-(\d*)',request)
                            if not match:raise ValueError('Single explicit byte range required')
                            begin=int(match[1]);end=min(size-1,int(match[2])) if match[2] else size-1
                            if not 0<=begin<=end<size:raise ValueError('Range outside dataset')
                        self.send_response(206 if request else 200);self.send_header('Content-Type','application/x-hdf5')
                        self.send_header('Content-Disposition','attachment; filename="'+file.name+'"');self.send_header('Accept-Ranges','bytes')
                        self.send_header('Content-Length',str(end-begin+1))
                        if request:self.send_header('Content-Range',f'bytes {begin}-{end}/{size}')
                        self.end_headers()
                        with file.open('rb') as f:
                            f.seek(begin);remaining=end-begin+1
                            while remaining:
                                block=f.read(min(1024**2,remaining));self.wfile.write(block);remaining-=len(block)
                        return
                    if path=='/api/health':self.reply(200,dict(status='ready',UI='Viser',backend='native_Sionna_prepared_geometry_preview_and_real_stored_replay',port=ui.port));return
                    if path=='/api/config':self.reply(200,ui.controller.config);return
                    if path=='/api/config-download':
                        data=json.dumps(plain(ui.controller.export_actions() if ui.controller.replay is None else ui.controller.config),ensure_ascii=False,indent=2).encode()
                        self.send_response(200);self.send_header('Content-Type','application/json');self.send_header('Content-Disposition','attachment; filename="wiwo_experiment.json"');self.send_header('Content-Length',str(len(data)));self.end_headers();self.wfile.write(data);return
                    if path=='/api/analysis':self.reply(200,ui.stored_analysis());return
                    if path=='/api/preflight':self.reply(200,ui.preflight_status());return
                    if path=='/api/estimate':self.reply(200,ui.refresh_estimate());return
                    if path=='/api/ui':self.reply(200,ui.telemetry());return
                    if path=='/api/state':
                        csi=None if r is None else {k:v for k,v in r.items() if k not in ('H','paths','_tx_coordinates','_geometry_sha256')}
                        if csi is not None:csi.update(shape=list(r['H'].shape),path_count=len(r.get('paths',[])))
                        self.reply(200,dict(state=s,statistics=stats,csi=csi));return
                    if path=='/api/csi':
                        self.reply(200,dict(available=False,scope='Unknown_not_computed') if r is None else dict(available=True,real=r['H'].real,imag=r['H'].imag,
                            axes=['user','rx_antenna','tx_antenna','subcarrier'],timestamp=r['physical_timestamp'],label_source=r['label_source'],independent_validation=r['independent_validation_status'],matches_current_geometry=stats['current_CSI']!='Unknown_current_pose',current_pose_status=stats['current_CSI']));return
                    self.reply(404,dict(error='Unknown route'))
                except Exception as e:self.reply(400,dict(error=str(e)))
            def do_POST(self):
                try:
                    n=int(self.headers.get('Content-Length',0))
                    if not 0<n<=4*1024**2:raise ValueError('Invalid JSON payload size')
                    q=json.loads(self.rfile.read(n))
                    if self.path=='/api/control':
                        if q['operation']=='claim':session=ui.sessions.api_claim();self.reply(200,dict(session=session,control=ui.sessions.view()));return
                        if q['operation']=='release':ui.sessions.release(self.headers.get('X-Wiwo-Control-Session'));ui.lease_bridge.refresh();self.reply(200,dict(released=True));return
                        raise ValueError('Unknown control operation')
                    session=self.headers.get('X-Wiwo-Control-Session')
                    with ui.render_lock:
                        ui.sessions.require(session,q.pop('_revision',None))
                        self._mutate(q)
                except PermissionError as exc:self.reply(409,dict(error=str(exc),control=ui.sessions.view()))
                except Exception as exc:self.reply(400,dict(error=type(exc).__name__+': '+str(exc)))
            def _mutate(self,q):
                try:
                    if self.path=='/api/action':r=ui.controller.action(q)
                    elif self.path=='/api/command':r=ui.command(q['kind'],q.get('payload'))
                    elif self.path=='/api/config':r=ui.configure(q)
                    elif self.path=='/api/preflight':r=ui.start_preflight()
                    elif self.path=='/api/preset':r=ui.save_preset(q['name'])
                    elif self.path=='/api/trajectory':
                        c=deepcopy(ui.controller.config);key={'user':'users','actor':'actors','bs':'base_stations'}[q['entity']]
                        node=next(x for x in c[key] if x['id']==q['id']);node['trajectory']=q['waypoints'];node['position_m']=q['waypoints'][0]['position_m'];node['orientation_deg']=q['waypoints'][0].get('orientation_deg',[0,0,0])
                        if 'motion' not in q:raise ValueError('Explicit bounded motion limits required; old trajectories remain available via complete config import')
                        node['motion']=q['motion'];r=ui.configure(c)
                    else:self.reply(404,dict(error='Unknown route'));return
                    ui.sessions.mutation(self.headers.get('X-Wiwo-Control-Session'),'accepted_API_mutation')
                    self.reply(200,dict(result=r,control=ui.sessions.view()))
                except Exception as exc:self.reply(400,dict(error=type(exc).__name__+': '+str(exc)))
        self.server=ThreadingHTTPServer((host,port),Handler);self.thread=threading.Thread(target=self.server.serve_forever,daemon=True);self.thread.start()
    def close(self):self.server.shutdown();self.server.server_close();self.thread.join(timeout=3)


