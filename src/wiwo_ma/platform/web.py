def serve(config,host='127.0.0.1',port=8080,authorization=None,replay=None):
    import faulthandler,signal
    faulthandler.register(signal.SIGUSR1,all_threads=True)
    controller=PlatformController(config,authorization=authorization);ui=None
    try:
        if replay is not None:controller.command('load_dataset',dict(path=replay))
        ui=PlatformUI(controller,host,port);ui.run()
    except KeyboardInterrupt:pass
    finally:
        if ui:ui.close()
        else:controller.close()
