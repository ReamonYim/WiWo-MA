    def _submit_action(self,payload):
        result=self.controller.action(payload);s=self.controller.state()
        commands=payload.get('actions',[payload]);keys={(x['bs_id'],x['panel_id']) for x in commands}
        indices=[i for i,key in enumerate(s['panel_ids']) if tuple(key) in keys]
        no_op=not result.get('effective_time_s',s['timestamp'])>s['timestamp'] and all(x.get('type')=='target_pose' for x in commands) and all(
            np.allclose(s['positions'][i],s['target_positions'][i],rtol=0,atol=1e-12) and
            np.allclose(s['rotations'][i],s['target_rotations'][i],rtol=0,atol=1e-12) and
            np.linalg.norm(s['velocities'][i])<1e-12 and np.linalg.norm(s['angular_velocities'][i])<1e-12 for i in indices)
        self.action_submission=dict(stage='NoOp' if no_op else 'Submitted',physical_time_s=s['timestamp'],
            configuration_sha256=s['configuration_sha256'],indices=indices,draft_revision=self.draft_revision,
            command_ids=[s['mechanics'][i]['command_id'] for i in indices],
            start_positions=[plain(s['positions'][i]) for i in indices],start_rotations=[plain(s['rotations'][i]) for i in indices],
            awaiting_control_tick=bool(result.get('effective_time_s',s['timestamp'])>s['timestamp']),
            effective_time_s=result.get('effective_time_s',s['timestamp']),
            submitted_action=deepcopy(payload),receipt=deepcopy(result),
            notice='目标已位于当前姿态：没有新的位移/转动请求（重复相同目标）' if no_op else None)
